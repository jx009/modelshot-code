  expect(project.sections[0].title).toBe("把日常，过成喜欢的样子");
  const meta = await sharp(await zip.file("detail-page.png").async("nodebuffer")).metadata();
  expect(meta.width).toBe(750); expect(meta.height).toBe(5178);
  await page.screenshot({ path: info.outputPath("commerce-storyboard.png"), fullPage: false });
  await page.goto("/zh/commerce");
  await expect(page.getByLabel("标题", { exact: true })).toHaveValue("把日常，过成喜欢的样子");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
  await page.goto("/zh");
  await page.getByRole("tab", { name: /电商套图 Agent/ }).click();
  await page.getByLabel("产品名称", { exact: true }).fill("黄铜台灯");
  await page.getByLabel("品牌名", { exact: true }).fill("暮光");
