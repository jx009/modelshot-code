// @vitest-environment jsdom
import { act, cleanup, renderHook, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { useWebArtifact } from "../../src/components/creation/useWebArtifact";
import { webSchema } from "../../src/lib/creation/contracts/web.js";
const mocks = vi.hoisted(() => ({ api: vi.fn(), read: vi.fn(), write: vi.fn() }));
vi.mock("../../src/lib/client-api", () => ({ api: (...args) => mocks.api(...args), requestKey: () => "stable-web-key-12345" }));
vi.mock("../../src/lib/creation/client/drafts", () => ({ readArtifactDraft: (...args) => mocks.read(...args), writeArtifactDraft: (...args) => mocks.write(...args) }));
vi.mock("../../src/lib/studio/project-list", () => ({ invalidateProjectLists: vi.fn() }));
const site = () => webSchema.parse({ schemaVersion: 1, kind: "web", title: "Coffee", theme: { primary: "#111111", accent: "#ee5500", background: "#ffffff", fontFamily: "sans" }, entryPath: "index.html", files: [{ id: "html", path: "index.html", kind: "html", content: "<h1>Coffee</h1>" }] });
beforeEach(() => { Object.values(mocks).forEach(mock => mock.mockReset()); mocks.read.mockResolvedValue(null); mocks.write.mockResolvedValue(undefined); mocks.api.mockResolvedValue({ revision: 2, content: site() }); });
afterEach(cleanup);
it("persists a restore request before sending, freezes edits and replays the exact request after a lost response", async () => {
  const { result, unmount } = renderHook(() => useWebArtifact("u", "a", "web-session-123456"));
  await waitFor(() => expect(result.current.ready).toBe(true));
  mocks.api.mockRejectedValueOnce(new Error("Lost response"));
  await act(async () => { await expect(result.current.restoreRevision(1)).rejects.toThrow("Lost response"); });
  expect(result.current.restorePending).toMatchObject({ baseRevision: 2, restoreRevision: 1 });
  const first = mocks.api.mock.calls.find(([, options]) => options?.method === "POST");
  expect(first[0]).toBe("/api/creation/artifacts/a/web/restore");
  expect(mocks.write.mock.invocationCallOrder[0]).toBeLessThan(mocks.api.mock.invocationCallOrder[1]);
  expect(result.current.change([{ op: "setFile", fileId: "html", path: "index.html", kind: "html", content: "New" }])).toBe(false);
  await expect(result.current.flush()).rejects.toThrow("ARTIFACT_NOT_READY");
  const persisted = structuredClone(mocks.write.mock.calls.at(-1)[2]);
  unmount(); mocks.read.mockResolvedValue(persisted);
  const remounted = renderHook(() => useWebArtifact("u", "a", "web-session-123456"));
  await waitFor(() => expect(remounted.result.current.ready).toBe(true));
  const posts = mocks.api.mock.calls.filter(([, options]) => options?.method === "POST");
  expect(posts).toHaveLength(2); expect(posts[1][1].body).toEqual(posts[0][1].body); expect(remounted.result.current.restorePending).toBeNull();
});
it("opens the newer cloud version after a confirmed restore CAS rejection", async () => {
  const { result } = renderHook(() => useWebArtifact("u", "a", "web-session-123456"));
  await waitFor(() => expect(result.current.ready).toBe(true));
  mocks.api.mockRejectedValueOnce(Object.assign(new Error("Conflict"), { code: "ARTIFACT_VERSION_CONFLICT" }));
  await act(async () => { await expect(result.current.restoreRevision(1)).rejects.toThrow("Conflict"); });
  await waitFor(() => expect(result.current.status).toBe("saved"));
  expect(result.current.restorePending).toBeNull();
  expect(mocks.write.mock.calls.at(-1)[2].restoreRequest).toBeNull();
});
it("includes unfinished source in an explicit conflict copy and preserves cloud contents", async () => {
  const source = site();
  mocks.read.mockResolvedValue({ baseRevision: 1, content: source, operations: [{ op: "setFile", fileId: "html", path: "index.html", kind: "html", content: "<h1>Coffee</h1>" }], inflight: null });
  const { result } = renderHook(() => useWebArtifact("u", "a", "web-session-123456"));
  await waitFor(() => expect(result.current.status).toBe("conflict"));
  const pending = { kind: "web-source", fileId: "html", path: "index.html", fileKind: "html", original: source.files[0].content, text: "<h1>Unfinished</h1>", composing: false };
  mocks.api.mockResolvedValueOnce({ artifactId: "copy", revision: 1 });
  await act(async () => { await result.current.saveConflictCopy("Local copy", pending); });
  const call = mocks.api.mock.calls.find(([, options]) => options?.method === "POST");
  expect(call[0]).toBe("/api/creation/artifacts/a/web/copy"); expect(call[1].body.content.files[0].content).toBe("<h1>Unfinished</h1>");
  expect(result.current.content.files[0].content).toBe("<h1>Coffee</h1>");
});
it("journals file creation and its undo/redo through the same web endpoint", async () => {
  const { result } = renderHook(() => useWebArtifact("u", "a", "web-session-123456"));
  await waitFor(() => expect(result.current.ready).toBe(true));
  const file = { id: "css", kind: "css", path: "styles.css", content: "/* css */" };
  act(() => { result.current.change([{ op: "insertFile", file }]); });
  expect(result.current.content.files).toHaveLength(2);
  act(() => { result.current.undo(); }); expect(result.current.content.files).toHaveLength(1);
  act(() => { result.current.redo(); }); expect(result.current.content.files[1]).toEqual(file);
  mocks.api.mockResolvedValue({ revision: 3 });
  await act(async () => { await result.current.flush(); });
  const call = mocks.api.mock.calls.find(([, options]) => options?.method === "PATCH");
  expect(call[0]).toBe("/api/creation/artifacts/a/web");
  expect(call[1].body.operations.map(operation => operation.op)).toEqual(["insertFile", "removeFile", "insertFile"]);
});
it("refuses deletion when its undo cannot fit the transport budget", async () => {
  const content = site(); content.files.push({ id: "large", path: "large.css", kind: "css", content: "/*" + "x".repeat(250 * 1024) + "*/" });
  mocks.api.mockResolvedValue({ revision: 1, content });
  const { result } = renderHook(() => useWebArtifact("u", "a", "web-session-123456"));
  await waitFor(() => expect(result.current.ready).toBe(true));
  expect(() => result.current.change([{ op: "removeFile", fileId: "large", path: "large.css" }])).toThrow("WEB_UNDO_BATCH_TOO_LARGE");
  expect(result.current.content.files).toHaveLength(2); expect(result.current.undoCount).toBe(0);
});
