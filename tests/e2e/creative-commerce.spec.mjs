  await expect(page.getByLabel("目标平台", { exact: true })).toHaveValue("shopify");
  await expect(page.getByLabel("地区", { exact: true })).toHaveValue("US");
  await expect(page.getByLabel("文案语言", { exact: true })).toHaveValue("en");
  await page.getByLabel("品牌名", { exact: true }).fill("暮光 2");
  await page.reload();
