test("commerce keeps two image roles, six independent jobs, replay and cloud recovery", async ({ page }, info) => {
  const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: getTestEnvironment().databaseUrl }) });
  const email = `commerce-${info.project.name}-${Date.now()}@modelshot.test`;
  try {
    const user = await db.user.create({ data: { email, passwordHash: await bcrypt.hash(E2E_PASSWORD, 10), credits: 300, emailVerified: new Date() } });
    await page.goto("/en/login?callbackUrl=/en/commerce?case=quiet-living");
    await page.getByRole("button", { name: "Email", exact: true }).click();
    await page.getByLabel("Email", { exact: true }).fill(email); await page.getByLabel("Password", { exact: true }).fill(E2E_PASSWORD); await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(page.getByLabel("Product name", { exact: true })).toHaveValue("Lounge chair");
    await page.goto("/en");
    await page.getByRole("tab", { name: /Commerce Agent/ }).click();
    await page.getByLabel("Product name", { exact: true }).fill("Lounge chair");
    await page.getByLabel("Upload product image", { exact: true }).setInputFiles("public/inspiration/chair.webp");
    await expect(page.locator(".cr-home-image img")).toHaveCount(1);
    await page.getByLabel("Upload style reference", { exact: true }).setInputFiles("public/inspiration/skincare.webp");
    await expect(page.locator(".cr-home-image img")).toHaveCount(2);
    await page.getByRole("button", { name: "Start product story", exact: true }).click();
    await expect(page.locator(".cm-upload.has-image")).toHaveCount(2);
    const saved = page.waitForResponse(r => r.url().endsWith("/api/studio/documents") && r.request().method() === "POST");
    await page.getByRole("button", { name: "Create storyboard", exact: true }).click();
    const doc = await (await saved).json(); expect(doc.content.commerce.productAssetId).not.toBe(doc.content.commerce.referenceAssetId);
    const submitted = page.waitForResponse(r => r.url().endsWith("/api/commerce/run"));
    await page.getByRole("button", { name: /Generate remaining sections/ }).click();
    const response = await submitted, submittedBody = response.request().postDataJSON(), result = await response.json();
    expect(result.failure).toBeNull(); expect(result.jobs).toHaveLength(6);
    const replay = await page.request.post("/api/commerce/run", { data: submittedBody }); expect((await replay.json()).jobs.map(j => j.id)).toEqual(result.jobs.map(j => j.id));
    await expect.poll(async () => (await db.tryOn.findMany({ where: { id: { in: result.jobs.map(j => j.id) } } })).filter(j => j.status === "succeeded").length, { timeout: 60000 }).toBe(6);
    const rows = await db.tryOn.findMany({ where: { id: { in: result.jobs.map(j => j.id) } } });
    expect(rows.every(j => j.snapshot.assetId === doc.content.commerce.productAssetId)).toBe(true);
    expect(rows.every(j => j.snapshot.referenceAssetIds[0] === doc.content.commerce.referenceAssetId)).toBe(true);
    expect((await db.user.findUnique({ where: { id: user.id } })).credits).toBe(192);
    await page.goto(`/en/commerce?document=${doc.id}`);
    await expect(page.getByRole("button", { name: "Download generated set", exact: true })).toBeEnabled();
    const download = page.waitForEvent("download"); await page.getByRole("button", { name: "Download generated set", exact: true }).click();
    expect((await download).suggestedFilename()).toBe("modelshot-product-story.zip");
    await page.getByRole("button", { name: "Continue in canvas", exact: true }).click();
    await expect(page).toHaveURL(/studio-v2\?document=/, { timeout: 40000 });
    await expect(page.locator(".ms-canvas-label")).toContainText("24 layers");
    await page.goto("/en/projects");
    await expect(page.locator(".cr-project-card")).toHaveCount(2);
  } finally { await db.$disconnect(); }
});
